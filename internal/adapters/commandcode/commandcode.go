// Package commandcode reads the local history of Command Code (the
// "command-code" npm CLI, binaries cmd, cmdc, commandcode, command-code).
//
// Layout (Windows; verified against command-code 1.32.1, its bundled source
// and the structure of the owner's files):
//
//	<home>\.commandcode\projects\<slug>\<id>.jsonl       one session, one entry per line
//	<home>\.commandcode\projects\<slug>\<id>.meta.json   {title, userRenamed, model, traceIds,
//	                                                     entrypoint, parentSessionId, forkedAt, ...}
//	<home>\.commandcode\projects\<slug>\<id>.checkpoints.jsonl, .prompts.jsonl,
//	                                     .share.json, .v2.bak   (not read)
//	<home>\.commandcode\history.jsonl                    input history (not read, see below)
//
// <home> is %HOME% when set, else %USERPROFILE% (Command Code's own rule), so
// both are scanned. <slug> is derived from the launch folder and is never
// decoded. Folders nested inside a project folder are not read. A transcript
// is any "*.jsonl" whose name does not contain ".checkpoints.", ".prompts."
// or ".v2.bak" (the CLI's own rule); the file stem is the session id that
// "cmdc --resume <id>" takes. Sub-agents run in memory and have no files.
//
// Transcript format v3 (current): the first line is a header
// {type:"session", version:3, id, timestamp (ISO), cwd}; every other line is
// an entry {type, id, parentId, timestamp, ...}:
//   - message: {message: {role: user|assistant, content: [blocks], meta}}.
//     Blocks are Anthropic-style: text, image, thinking, tool_use {name, input},
//     tool_result {tool_use_id, content: string | [text blocks]}.
//     meta: {source, createdAt (ms), messageId, isMeta, isAutomated, isSummary}.
//   - session_info {name}: the user's name for the session (the latest one
//     counts; one without a name clears it).
//   - model_change, effort_change, label, custom, compaction {summary},
//     branch_summary {summary}, custom_message {customType, content, display}:
//     not conversation text; they only count as activity.
//
// Entries form a tree through parentId (rewinds and edits add branches). All
// message entries are kept in file order, abandoned branches included, so no
// text is lost.
//
// Older formats, read the same way: v2 lines {id, timestamp, sessionId,
// parentId, role: user|assistant|tool, content: string | [parts], metadata:
// {version:2, ...meta}} with parts text, reasoning, image {image},
// tool-call {toolName, input}, tool-result {toolName, output}; v1 (legacy)
// lines {role, content (Anthropic blocks), timestamp, metadata?}. They carry
// no cwd, so Cwd stays empty for them.
//
// Rules:
//   - Cwd = the first header's cwd; a later header never changes it.
//   - User messages with meta isMeta (hidden context) or isSummary
//     (compaction summary) are skipped. meta.source "user", "followup" and
//     "steering" (typed by the user, also while the agent works) and no source
//     give RoleUser text; "tool" gives tool output; isAutomated (stop hooks)
//     and any other source ("mod:<name>", ...) give RoleSystem text.
//   - The CLI's own notices, stored as user messages without a source
//     ("Error: ...", "Interrupted by user", "Insufficient credits"), become
//     RoleSystem text.
//   - Thinking/reasoning blocks are dropped; images become "[image]";
//     consecutive text blocks of one message are joined with "\n".
//   - Tool calls become "name: <command | file_path | path | pattern | url |
//     query | description | first 200 runes of the input>"; tool outputs keep
//     model.MaxToolOutput bytes of their text.
//   - Title: the latest named session_info, or meta.json title with
//     userRenamed (TitleUser); else meta.json title, generated by the agent or
//     copied from a fork's parent (TitleAgent); else the first real prompt
//     (TitlePrompt, 100 runes, whitespace collapsed).
//   - StartedAt/UpdatedAt: min/max of every entry time (message times fall
//     back to meta.createdAt); the file's mtime when no time is recorded.
//   - Sessions without any message left are not returned. Headless ("print")
//     sessions are kept: they are the user's own runs.
//   - A torn .meta.json modified less than 5 s ago is being rewritten: Read
//     returns an error wrapping adapters.ErrRetryLater and sync retries the
//     source next time. An older torn or unreadable one only loses its title
//     and adds a warning.
//
// history.jsonl is the CLI's input history (arrow-up recall): {p: text,
// t: epoch ms} per line, at most 1000 entries, rewritten whole on every
// prompt. It records no session id and no folder, so its prompts cannot be
// attached to a session (spec §4.5 creates prompt sessions only "for session
// ids with no transcript") and it is not read.
package commandcode

import (
	"github.com/AbuDergham/Athar/internal/adapters"
)

type adapter struct{}

// New returns the Command Code adapter (used by internal/registry).
func New() adapters.Adapter { return adapter{} }

func (adapter) ID() string   { return "commandcode" }
func (adapter) Name() string { return "Command Code" }

// Version is bumped whenever parsing changes; sources are then re-read in full.
func (adapter) Version() int { return 1 }

// Caps: on Windows the resume command is "cmdc" because the CLI's "cmd"
// shim is shadowed by cmd.exe (per the CLI's changelog). --resume accepts the
// session id and looks it up in the launch folder's project directory, so
// launch must start it in Cwd.
func (adapter) Caps() adapters.Caps {
	return adapters.Caps{
		Resume:            []string{"cmdc", "--resume", "{id}"},
		ProgramCandidates: []string{`%APPDATA%\npm\cmdc.cmd`},
		Fork:              []string{"--fork-session"},
		SkipPermissions:   []string{"--dangerously-skip-permissions"},
	}
}
