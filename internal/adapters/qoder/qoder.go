// Package qoder reads the local history of Qoder CLI (qodercli).
//
// Layout (Windows, verified against qodercli 0.1.3 data):
//
//	%USERPROFILE%\.qoder\projects\<enc>\<id>.jsonl          one session, one JSON record per line
//	%USERPROFILE%\.qoder\projects\<enc>\<id>-session.json   session metadata
//
// <enc> is the launch folder with ':' and '\' replaced by '-'. It is never
// decoded: Cwd comes only from working_dir in the metadata file, and is empty
// when that file is missing. Folders nested inside a project folder are not read.
//
// Metadata file: {id, parent_session_id, title, working_dir, summary_message_id,
// created_at, updated_at (epoch ms), message_count, prompt_tokens, completion_tokens, cost}.
// title is generated by the agent; "New Session" is its placeholder.
//
// Transcript record: {id, parent_id, session_id, role: user|assistant|tool,
// is_meta, parts: [{type, data}], model, provider, usage,
// created_at, updated_at, finished_at (epoch ms)}. Part types seen in data:
// text {text}; tool_call {id, name, input (JSON text), type, finished};
// tool_result {tool_use_id, content, metadata}; finish {reason, time}.
// The qodercli binary also has reasoning, image-URL and binary content types;
// "reasoning" is dropped and "image_url"/"image"/"binary" become "[image]"
// (those type names are inferred, not yet seen in data). Unknown parts are dropped.
//
// Rules:
//   - is_meta records (slash-command wrappers, their output, caveats) are skipped;
//     so are user texts that are such wrappers, and <system-reminder> blocks are
//     removed from user text.
//   - The record named by summary_message_id (a compaction summary) is skipped.
//   - Sessions with a parent_session_id (sub-agent sessions) are skipped entirely,
//     and so are sessions that have no message left.
//   - Reasoning and finish parts are dropped; images become "[image]".
//   - Tool calls become "name: <command | file_path | pattern | path | url | query
//     | first 200 runes of the input>"; tool outputs keep model.MaxToolOutput bytes.
//   - Title: the metadata title (TitleAgent) unless it is empty or "New Session",
//     else the first real prompt (TitlePrompt, 100 runes, whitespace collapsed).
//   - StartedAt/UpdatedAt: min/max of every record time and the metadata times;
//     the transcript's mtime when no time is recorded at all.
package qoder

import (
	"errors"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"strings"

	"github.com/AbuDergham/Athar/internal/adapters"
)

const (
	adapterID = "qoder"
	// metaSuffix turns "<id>" into the metadata file name "<id>-session.json".
	metaSuffix = "-session.json"
)

// sessionFileID matches the file stem of a session transcript. Stems with a dot
// (e.g. "x.v2.jsonl") are sidecars, not sessions.
var sessionFileID = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9_-]*$`)

type adapter struct{}

// New returns the Qoder CLI adapter (used by internal/registry).
func New() adapters.Adapter { return adapter{} }

func (adapter) ID() string   { return adapterID }
func (adapter) Name() string { return "Qoder CLI" }
func (adapter) Version() int { return 1 }

// Caps: qodercli 0.1.3 documents --resume <id> and --dangerously-skip-permissions.
// Qoder has no data-root environment variable and no fork flag.
func (adapter) Caps() adapters.Caps {
	return adapters.Caps{
		Resume:            []string{"qodercli", "--resume", "{id}"},
		ProgramCandidates: []string{`%APPDATA%\npm\qodercli.cmd`},
		SkipPermissions:   []string{"--dangerously-skip-permissions"},
	}
}

// Sources returns one source per session transcript. Files lists the
// transcript and its metadata file (which may not exist) so that a change in
// either triggers a re-read.
func (adapter) Sources(env adapters.Env) ([]adapters.Source, error) {
	if env.Home == "" {
		return nil, nil
	}
	projects := filepath.Join(env.Home, ".qoder", "projects")
	dirs, err := os.ReadDir(projects)
	if err != nil {
		if errors.Is(err, fs.ErrNotExist) {
			return nil, nil
		}
		return nil, err
	}
	var out []adapters.Source
	for _, d := range dirs {
		if !d.IsDir() {
			continue
		}
		dir := filepath.Join(projects, d.Name())
		files, err := os.ReadDir(dir)
		if err != nil {
			continue // vanished or unreadable project folder: nothing to read
		}
		for _, f := range files {
			name := f.Name()
			if f.IsDir() || !strings.HasSuffix(name, ".jsonl") {
				continue
			}
			if !sessionFileID.MatchString(strings.TrimSuffix(name, ".jsonl")) {
				continue
			}
			p := filepath.Join(dir, name)
			out = append(out, adapters.Source{
				Adapter: adapterID,
				Path:    p,
				Files:   []string{p, metaPath(p)},
			})
		}
	}
	return out, nil
}

// metaPath returns the metadata file of a transcript: <dir>\<id>-session.json.
func metaPath(transcript string) string {
	return strings.TrimSuffix(transcript, ".jsonl") + metaSuffix
}
