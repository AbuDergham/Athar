const (
	id = "cursor"
	// Source.Extra keys: the locations Sources found, so Read looks at the same ones.
	extraDB        = "db"
	extraWorkspace = "workspaceStorage"
	extraProjects  = "projects"
)

type adapter struct{}

// New returns the Cursor IDE adapter (used by internal/registry).
func New() adapters.Adapter { return adapter{} }

func (adapter) ID() string   { return id }
func (adapter) Name() string { return "Cursor" }
func (adapter) Version() int { return 1 }

// locations are Cursor's data folders for one user.
type locations struct {
	db         string // globalStorage\state.vscdb
	workspaces string // workspaceStorage
	projects   string // ~\.cursor\projects
}

func defaultLocations(env adapters.Env) locations {
	var l locations
	if env.AppData != "" {
		user := filepath.Join(env.AppData, "Cursor", "User")
		l.db = filepath.Join(user, "globalStorage", "state.vscdb")
		l.workspaces = filepath.Join(user, "workspaceStorage")
	}
	if env.Home != "" {
		l.projects = filepath.Join(env.Home, ".cursor", "projects")
	}
	return l
}

func sourceLocations(env adapters.Env, src adapters.Source) locations {
	l := defaultLocations(env)
	if v, ok := src.Extra[extraDB]; ok {
		l.db = v
	}
	if v, ok := src.Extra[extraWorkspace]; ok {
		l.workspaces = v
	}
	if v, ok := src.Extra[extraProjects]; ok {
		l.projects = v
	}
	return l
}

// Sources returns one Source when Cursor's global database or any agent
// transcript exists. Its Files are the global database (with sidecars), each
// workspace.json and workspace database of a folder workspace, and every
// transcript, so a change to any of them re-reads the source.
func (adapter) Sources(env adapters.Env) ([]adapters.Source, error) {
	l := defaultLocations(env)
	hasDB := isFile(l.db)
	transcripts := listTranscripts(l.projects)
	if !hasDB && len(transcripts) == 0 {
		return nil, nil
	}
	src := adapters.Source{
		Adapter: id,
		Extra:   map[string]string{extraDB: l.db, extraWorkspace: l.workspaces, extraProjects: l.projects},
	}
	if hasDB {
		src.Path = l.db
		src.Files = append(src.Files, fsread.SQLiteSidecars(l.db)...)
	} else {
		src.Path = l.projects
	}
	for _, w := range listWorkspaces(l.workspaces) {
		src.Files = append(src.Files, w.jsonPath)
		if isFile(w.dbPath) {
			src.Files = append(src.Files, fsread.SQLiteSidecars(w.dbPath)...)
		}
	}
	for _, t := range transcripts {
		src.Files = append(src.Files, t.path)
	}
	return []adapters.Source{src}, nil
}

// Read reads every chat of the global database and every agent transcript.
func (adapter) Read(ctx context.Context, env adapters.Env, src adapters.Source) (adapters.ReadResult, error) {
	var res adapters.ReadResult
	if err := ctx.Err(); err != nil {
		return res, err
	}
	l := sourceLocations(env, src)
	transcripts := map[string]transcript{}
	var transcriptOrder []string
	for _, t := range listTranscripts(l.projects) {
		if _, dup := transcripts[t.id]; !dup {
			transcripts[t.id] = t
			transcriptOrder = append(transcriptOrder, t.id)
		}
	}
	ws := newWorkspaceIndex(env, l.workspaces)
	used := map[string]bool{} // transcript ids consumed by a chat of the database

	if isFile(l.db) {
		sessions, err := readGlobal(ctx, env, l.db, ws, transcripts, used, &res)
		if err != nil {
			return adapters.ReadResult{}, err
		}
		res.Sessions = append(res.Sessions, sessions...)
	}
	res.Warnings = append(res.Warnings, ws.warnings...)

	known := ws.folders()
	for _, s := range res.Sessions {
		if s.Cwd != "" {
			known = append(known, s.Cwd)
		}
	}
	for _, tid := range transcriptOrder {
		if used[tid] {
			continue
		}
		if err := ctx.Err(); err != nil {
			return adapters.ReadResult{}, err
		}
		t := transcripts[tid]
		msgs, skipped, err := parseTranscript(t.path)
		res.Skipped += skipped
		if err != nil {
			res.Warnings = append(res.Warnings, fmt.Sprintf("transcript %s: %v", filepath.Base(t.path), err))
			continue
		}
		if len(msgs) == 0 {
			continue
		}
		s := model.Session{
			Agent:    id,
			NativeID: t.id,
			Cwd:      matchSlug(t.slug, known),
			Coverage: model.CoverageFull,
			Origin:   model.OriginLive,
			Messages: msgs,
		}
		s.Title, s.TitleSource = promptTitleOf(msgs)
		var mtime time.Time
		if _, mt, err := fsread.Stat(t.path); err == nil {
			mtime = mt.UTC()
		}
		setTimes(&s, time.Time{}, mtime, mtime)
		res.Sessions = append(res.Sessions, s)
	}
	return res, nil
}

// readGlobal reads the chats of the global database from a private copy.
func readGlobal(ctx context.Context, env adapters.Env, dbPath string, ws *workspaceIndex,
	transcripts map[string]transcript, used map[string]bool, res *adapters.ReadResult) ([]model.Session, error) {
	copyPath, cleanup, err := fsread.CopySQLite(dbPath, env.TempDir)
	if err != nil {
		return nil, err
	}
	defer cleanup()
	db, err := fsread.OpenSQLiteCopy(copyPath)
	if err != nil {
		return nil, err
	}
	defer db.Close()

	if !hasTable(db, "cursorDiskKV") {
		res.Warnings = append(res.Warnings, "state.vscdb has no cursorDiskKV table; format not recognized")
		return nil, nil
	}
	rows, err := keyRange(ctx, db, "composerData:")
	if err != nil {
		return nil, err
	}
	var out []model.Session
	for _, r := range rows {
		if err := ctx.Err(); err != nil {
			return nil, err
		}
		cid := strings.TrimPrefix(r.key, "composerData:")
		if r.value == nil {
			continue
		}
		c, ok := decodeComposer(r.value)
		if !ok {
			res.Skipped++
			continue
		}
		if c.ComposerID != "" {
			cid = c.ComposerID
		}
		s, ok, err := readComposer(ctx, db, cid, c, ws, transcripts, used, res)
		if err != nil {
			return nil, err
		}
		if ok {
			out = append(out, s)
		}
	}
	return out, nil
}

// readComposer turns one composerData row into a session; ok is false for a
// chat without messages.
func readComposer(ctx context.Context, db *sql.DB, cid string, c composer, ws *workspaceIndex,
	transcripts map[string]transcript, used map[string]bool, res *adapters.ReadResult) (model.Session, bool, error) {
	var bubbles []bubble
	missing := 0
	switch {
	case len(c.Headers) > 0:
		stored, err := keyRange(ctx, db, "bubbleId:"+cid+":")
		if err != nil {
			return model.Session{}, false, err
		}
		byID := make(map[string][]byte, len(stored))
		for _, r := range stored {
			byID[strings.TrimPrefix(r.key, "bubbleId:"+cid+":")] = r.value
		}
		for _, h := range c.Headers {
			raw := byID[h.BubbleID]
			if raw == nil {
				raw = c.ConversationMap[h.BubbleID]
			}
			b, ok := decodeBubble(raw)
			if !ok {
				missing++
				continue
			}
			if b.Type == 0 {
				b.Type = h.Type
			}
			bubbles = append(bubbles, b)
		}
	default:
		for _, raw := range c.Conversation {
			b, ok := decodeBubble(raw)
			if !ok {
				missing++
				continue
			}
			bubbles = append(bubbles, b)
		}
	}
	res.Skipped += missing
	msgs := bubbleMessages(bubbles)

	cwd := c.workspacePath()
	if cwd == "" {
		cwd = ws.folderOf(cid)
	}
	if cwd == "" {
		for _, b := range bubbles {
			if len(b.WorkspaceURIs) > 0 {
				cwd = fileURIPath(b.WorkspaceURIs[0])
				break
			}
		}
	}

	coverage := model.CoverageFull
	if missing > 0 {
		coverage = model.CoveragePartial
	}
	if len(msgs) == 0 {
		t, ok := transcripts[cid]
		if !ok {
			return model.Session{}, false, nil // an empty draft
		}
		tm, skipped, err := parseTranscript(t.path)
		res.Skipped += skipped
		used[cid] = true
		if err != nil {
			res.Warnings = append(res.Warnings, fmt.Sprintf("transcript %s: %v", filepath.Base(t.path), err))
		}
		if len(tm) == 0 {
			return model.Session{}, false, nil
		}
		msgs, coverage = tm, model.CoverageFull
		if cwd == "" {
			known := ws.folders()
			cwd = matchSlug(t.slug, known)
		}
	} else if _, ok := transcripts[cid]; ok {
		used[cid] = true // the database has the text; the transcript would duplicate it
	}

	s := model.Session{
		Agent:    id,
		NativeID: cid,
		Cwd:      cwd,
		Coverage: coverage,
		Origin:   model.OriginLive,
		Messages: msgs,
	}
	if name := strings.TrimSpace(c.Name); name != "" {
		s.Title, s.TitleSource = name, model.TitleAgent
	} else {
		s.Title, s.TitleSource = promptTitleOf(msgs)
	}
	setTimes(&s, msTime(c.CreatedAt), msTime(c.LastUpdatedAt), time.Time{})
	return s, true, nil
}

// setTimes sets StartedAt to the earliest and UpdatedAt to the latest of the
// chat's own times and its messages' times; fallback is used when none is known.
func setTimes(s *model.Session, created, updated, fallback time.Time) {
	var first, last time.Time
	see := func(t time.Time) {
		if t.IsZero() {
			return
		}
		if first.IsZero() || t.Before(first) {
			first = t
		}
		if last.IsZero() || t.After(last) {
			last = t
		}
	}
	see(created)
	see(updated)
	for _, m := range s.Messages {
		see(m.At)
	}
	see(fallback)
	s.StartedAt, s.UpdatedAt = first, last
}

// kv is one cursorDiskKV row; value is nil for SQL NULL.
type kv struct {
	key   string
	value []byte
}

// keyRange returns the rows whose key starts with prefix. prefix ends with
// ':', so the range [prefix, prefix with ';') is exactly the prefix and uses
// the key's unique index instead of scanning every value.
func keyRange(ctx context.Context, db *sql.DB, prefix string) ([]kv, error) {
	hi := strings.TrimSuffix(prefix, ":") + ";"
	rows, err := db.QueryContext(ctx, `SELECT key, value FROM cursorDiskKV WHERE key >= ? AND key < ? ORDER BY key`, prefix, hi)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var out []kv
	for rows.Next() {
		var r kv
		if err := rows.Scan(&r.key, &r.value); err != nil {
			return nil, err
		}
		out = append(out, r)
	}
	return out, rows.Err()
}

func hasTable(db *sql.DB, name string) bool {
	var n int
	err := db.QueryRow(`SELECT count(*) FROM sqlite_master WHERE type = 'table' AND name = ?`, name).Scan(&n)
	return err == nil && n > 0
}

func isFile(p string) bool {
	if p == "" {
		return false
	}
	fi, err := os.Stat(p)
	return err == nil && fi.Mode().IsRegular()
}

// decodeJSON unmarshals data into v. A syntax error fails; a field of an
// unexpected type only loses that field.
func decodeJSON(data []byte, v any) bool {
	err := json.Unmarshal(data, v)
	var te *json.UnmarshalTypeError
	return err == nil || errors.As(err, &te)
}

// Caps: Cursor cannot open a chat by id; Athar opens the project in Cursor
// and the user picks the chat from its history.
func (adapter) Caps() adapters.Caps {
	return adapters.Caps{
		App: &adapters.AppCommand{
			Name:    "Cursor",
			Program: "cursor",
			Args:    []string{"{cwd}"},
			Candidates: []string{
				`%ProgramFiles%\cursor\Cursor.exe`,
				`%LOCALAPPDATA%\Programs\cursor\Cursor.exe`,
			},
		},
	}
}
