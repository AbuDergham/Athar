// Package cursor reads the chat history of the Cursor IDE (Anysphere's VS
// Code fork): its "composer" chats (Ask, Agent and Edit modes) and, when a
// newer build or the Cursor CLI wrote them, its agent transcripts.
//
// Layout (%APPDATA%\Cursor\User):
//
//	globalStorage\state.vscdb   SQLite, tables ItemTable and cursorDiskKV (key TEXT, value JSON)
//	  cursorDiskKV composerData:<composerId>            one chat
//	  cursorDiskKV bubbleId:<composerId>:<bubbleId>     one message of that chat
//	workspaceStorage\<hash>\workspace.json              {"folder": "file:///d%3A/work/x"}
//	workspaceStorage\<hash>\state.vscdb                 ItemTable composer.composerData {allComposers[{composerId}]}
//
// and %USERPROFILE%\.cursor\projects\<path-slug>\agent-transcripts\<id>.jsonl|.txt
// (also <id>\<id>.jsonl; <id>\subagents\ is ignored).
//
// Rules learned from real files (Cursor 0.4x and 2.2):
//   - Everything is ONE Source: the global database plus the workspace
//     databases, workspace.json files and transcripts that give it projects
//     and text. The global database is only ever read from a CopySQLite copy,
//     with key-range queries (it can reach hundreds of MB and also holds auth
//     tokens in ItemTable, which is never queried).
//   - composerData: composerId, name (generated by Cursor, renamable; stored
//     as TitleAgent), createdAt / lastUpdatedAt (epoch ms). Message order is
//     fullConversationHeadersOnly[]{bubbleId, type 1 user / 2 assistant} with
//     one bubbleId row per message (_v 10+). The oldest builds (no _v) keep
//     the bubbles inline in conversation[]. conversationMap is consulted for a
//     header whose row is missing. Chats with no messages (most rows are
//     empty drafts) are skipped.
//   - Bubbles: text, createdAt (ISO 8601; inline bubbles only have
//     timingInfo.clientStartTime/clientEndTime in epoch ms). Tool calls are
//     assistant bubbles with toolFormerData{name, rawArgs (JSON string),
//     result (JSON string: output / contents), status, error}. Thinking
//     bubbles (capabilityType 30, empty text) and richText are not indexed.
//     A header whose bubble row is missing or NULL is counted in Skipped and
//     makes the session partial (users report updates that drop rows).
//   - Project (Cwd), first found: composerData.workspaceIdentifier.uri.fsPath
//     (newest builds); the workspace whose composer.composerData lists the
//     chat, via its workspace.json folder; the first bubble's
//     workspaceUris[0]. Empty windows (a workspaceStorage folder without
//     workspace.json) and multi-root workspaces (workspace.json "workspace")
//     give no folder. bubble.workspaceProjectDir is Cursor's own
//     ~\.cursor\projects folder, not the project.
//   - Agent transcripts are used for chats whose bubbles are absent and as
//     chats of their own (Cursor CLI). Their project slug (the path with every
//     non-alphanumeric run turned into "-") is never decoded: it only selects
//     a folder already known from workspace.json or a chat when exactly one
//     matches. JSONL records {role, message{content: string | [{type:text|
//     tool_use|tool_result}]}}; {"type":"turn_ended"} markers are ignored;
//     user turns are "<timestamp>Monday, Dec 15, 2025, 9:30 AM (UTC+3)</timestamp>
//     <user_query>…</user_query>" and only the query is kept. The .txt form
//     has "user:" / "assistant:" header lines. The transcript format was not
//     present on the owner's PC (Cursor 2.2 writes none); it follows
//     third-party reports and is parsed tolerantly.
//   - Not read: the Cursor CLI's ~\.cursor\chats\*\store.db (content-addressed
//     protobuf blobs, possibly encrypted) and the pre-composer
//     workbench.panel.aichat chat data of Cursor 0.2x/0.3x.
//   - No chat can be opened by id (Cursor's deeplinks only start new chats):
//     Athar opens the project in Cursor and the user picks the chat.
